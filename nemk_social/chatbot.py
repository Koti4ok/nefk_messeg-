def get_bot_answer(message: str) -> str:
    """Повертає відповідь бота на повідомлення користувача."""
    text = message.lower().strip()
    if not text:
        return random.choice(DEFAULT_ANSWERS)

    # ── Пошук найкращого збігу ────────────────────────────────
    best_match = None
    best_score = 0

    for entry in KNOWLEDGE_BASE:
        score = sum(1 for key in entry['keys'] if key in text)
        if score > best_score:
            best_score = score
            best_match = entry

    if best_match and best_score > 0:
        entry_type = best_match.get('_type')

        if entry_type == 'greeting':
            return random.choice(GREETINGS) + (
                '\n\nЗапитай мене про:\n'
                '📍 Адресу · 🎓 Спеціальності · 📅 Розклад\n'
                '🏠 Гуртожиток · 💰 Стипендію · ⚽ Спорт\n'
                '😄 Жарт · 💪 Мотивацію · і багато іншого!'
            )

        if entry_type == 'joke':
            return random.choice(JOKES)

        if entry_type == 'motivation':
            return random.choice(MOTIVATIONS_LIST)

        answer = best_match['answer']
        # Деякі відповіді отримують мотиваційний хвостик
        if random.random() < 0.3:
            motivation = random.choice(MOTIVATIONS)
            if motivation:
                answer += motivation
        return answer

    return random.choice(DEFAULT_ANSWERS)
