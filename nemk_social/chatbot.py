def get_bot_answer(message: str) -> str:
    """
    Повертає відповідь бота:
    1. Спробує Groq AI якщо є GROQ_API_KEY
    2. Якщо ні — rule-based база знань
    """
    text = message.lower().strip()
    if not text:
        return random.choice(DEFAULT_ANSWERS)

    # ── Спроба AI ─────────────────────────────────────────────
    ai_answer = _ask_groq(message)
    if ai_answer:
        return ai_answer

    # ── Rule-based fallback ───────────────────────────────────
    best_match = None
    best_score = 0
    for entry in KNOWLEDGE_BASE:
        score = sum(1 for key in entry['keys'] if key in text)
        if score > best_score:
            best_score = score
            best_match = entry

    if best_match and best_score > 0:
        t = best_match.get('_type')
        if t == 'greeting':
            return random.choice(GREETINGS) + '\n\nЗапитай про:\n📍 Адресу · 🎓 Спеціальності · 📅 Розклад · 😄 Жарт · 💪 Мотивацію'
        if t == 'joke':
            return random.choice(JOKES)
        if t == 'motivation':
            return random.choice(MOTIVATIONS)
        return best_match['answer']

    return random.choice(DEFAULT_ANSWERS)
